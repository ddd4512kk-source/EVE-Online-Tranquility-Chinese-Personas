const all = JSON.parse(fs.readFileSync('scratch/all-corps-details.json', 'utf8'));
const allSlugs = all.map(c => c.slug);

console.log(`Total expected slugs: ${allSlugs.length}`);
console.log(`Total epithets defined: ${Object.keys(EPITHETS).length}`);

let hasErr = false;

// Check missing or extra
for (const s of allSlugs) {
  if (!EPITHETS[s]) {
    console.error(`MISSING epithet for slug: ${s}`);
    hasErr = true;
  }
}
for (const k of Object.keys(EPITHETS)) {
  if (!allSlugs.includes(k)) {
    console.error(`EXTRA epithet for slug not in repo: ${k}`);
    hasErr = true;
  }
}

// Check lengths: strictly between 34 and 38
let minLen = 999, maxLen = 0;
for (const [slug, text] of Object.entries(EPITHETS)) {
  const len = text.length;
  if (len < minLen) minLen = len;
  if (len > maxLen) maxLen = len;
  if (len < 32 || len > 38) {
    console.error(`LENGTH OUT OF BOUNDS [${slug}] (${len} chars): "${text}"`);
    hasErr = true;
  }
}

console.log(`Min length: ${minLen}, Max length: ${maxLen}`);

if (hasErr) {
  console.error('Validation failed! Exiting without saving.');
  process.exit(1);
}

console.log('All 155 epithets validated! Updating JSON files...');

let updatedCount = 0;
for (const slug of allSlugs) {
  const jsonPath = path.join('src/corps', slug, `${slug}.json`);
  if (!fs.existsSync(jsonPath)) {
    console.error(`File not found: ${jsonPath}`);
    continue;
  }
  const raw = JSON.parse(fs.readFileSync(jsonPath, 'utf8'));
  raw.corp = raw.corp || {};
  raw.corp.epithet = EPITHETS[slug];
  fs.writeFileSync(jsonPath, JSON.stringify(raw, null, 2) + '\n', 'utf8');
  updatedCount++;
}

console.log(`Successfully updated ${updatedCount} corps JSON files with new epithets!`);
